    private void jButtonModifierActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonModifierActionPerformed
        // TODO add your handling code here:
        MissionDAO uneMissionDAO = new MissionDAO();
        Mission missionModif = new Mission(
                mission.getId(),
                jTextFieldTitre.getText(), 
                jTextFieldDescription.getText(),
                LocalDate.parse(jTextFieldDateD.getText()),
                LocalDate.parse(jTextFieldDafeF.getText()),
                Statut.valueOf(jComboBoxStatut.getSelectedItem().toString()),
                Priorite.valueOf(jComboBoxPriorite.getSelectedItem().toString()),
                Double.parseDouble(jTextFieldBudget.getText())
        );
        boolean reponse;
        try {
            reponse = uneMissionDAO.modifier(missionModif);
            if (reponse) {
                JOptionPane jop1;
                jop1 = new JOptionPane();
                jop1.showMessageDialog(null, "Modification reussie", "Information", JOptionPane.INFORMATION_MESSAGE);
            }
        MenuMission menu = new MenuMission();
        menu.setVisible(true);
        modifierMissionDialogue.this.dispose();
        } catch (SQLException ex) {
            System.getLogger(ModifierMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_jButtonModifierActionPerformed

    private void initialiserComboBox(){
        for (Statut statut : Statut.values()) {
            jComboBoxStatut.addItem(statut);
        }
        for (Priorite priorite : Priorite.values()) {
            jComboBoxPriorite.addItem(priorite);
        }
    }
    
    private void afficherMission() {
        jTextFieldTitre.setText(mission.getTitre());
        jTextFieldDescription.setText(mission.getDescription());
        jTextFieldDateD.setText(String.valueOf(mission.getDateDebut()));
        jTextFieldDafeF.setText(String.valueOf(mission.getDateFin()));
        jComboBoxStatut.setSelectedItem(mission.getStatut().name());
        jComboBoxPriorite.setSelectedItem(mission.getPriorite().name());
        jTextFieldBudget.setText(String.valueOf(mission.getBudget()));
    }
    
