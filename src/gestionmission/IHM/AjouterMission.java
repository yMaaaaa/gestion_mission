    private void ValiderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ValiderActionPerformed
        Mission missionAjout = new Mission(
        Titre.getText(), 
        Description.getText(), 
        LocalDate.parse(DateD.getText()), 
        LocalDate.parse(DateF.getText()),
        Statut.valueOf(jComboBoxStatut.getSelectedItem().toString()), 
        Priorite.valueOf(jComboBoxPriorite.getSelectedItem().toString()),
        Double.parseDouble(Budget.getText()));
        MissionDAO missionDao = new MissionDAO();
        try {
            int reponse = missionDao.ajouter(missionAjout);
            if(reponse == 1){
                JOptionPane jopl;
                jopl = new JOptionPane();
                jopl.showMessageDialog(null, "Ajout reussi", "Information", JOptionPane.INFORMATION_MESSAGE);
                MenuMission fenetreMenu = new MenuMission();
                fenetreMenu.setVisible(true);
                this.dispose();
            }
        } catch (SQLException ex) {
            System.getLogger(AjouterMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_ValiderActionPerformed

