    private void ouvrirMissionSelectionnee() throws SQLException{
        int ligneVue = jTableau.getSelectedRow();
        if (ligneVue == -1) {
            JOptionPane.showMessageDialog(this, "Sélectionner une mission.");
            return;
        }
        
        int ligneModele = jTableau.convertRowIndexToModel(ligneVue);
        int idMission = (int) jTableau.getModel().getValueAt(ligneModele, 0);
       
        
        MissionDAO dao = new MissionDAO();
            Mission mission = dao.trouverParId(idMission);
            modifierMissionDialogue dialogue = new modifierMissionDialogue(this, true, mission);
            dialogue.setVisible(true);
            initTable();
    }

