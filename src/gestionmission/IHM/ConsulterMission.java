    public void initTable() throws SQLException{
    String[] colonnes = { "ID", "Titre", "Description", "Date de début", "Date de fin", "Statut", "Priorite", "Budget" };
    
    DefaultTableModel modele = new DefaultTableModel(colonnes, 0);
    MissionDAO dao = new MissionDAO();
    for (Mission mission : dao.listerPreparer()) {
        Object[] ligne = {
            mission.getId(),
            mission.getTitre(),
            mission.getDescription(),
            mission.getDateDebut(),
            mission.getDateFin(),
            mission.getStatut(),
            mission.getPriorite(),
            mission.getBudget()
        };
        modele.addRow(ligne);
    }
    jTableau.setModel(modele);
    jTableau.setDefaultEditor(Object.class, null);
    jTableau.setAutoCreateRowSorter(true);
}
    
