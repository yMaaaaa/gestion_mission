    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        //Bouton valider
        MissionDAO uneMissionDAO = new MissionDAO();
        Mission missionRecup = (Mission) jComboBoxChoisirMission.getSelectedItem();
        Mission missionModif = new Mission(
                missionRecup.getId(), 
                jTextFieldTitre.getText(), 
                jTextFieldDescription.getText(),
                LocalDate.parse(jTextFieldDateD.getText()),
                LocalDate.parse(jTextFieldDateF.getText()),
                Statut.valueOf(jComboBoxStatut.getSelectedItem().toString()),
                Priorite.valueOf(jComboBoxPriorite.getSelectedItem().toString()),
                Double.parseDouble(jTextFieldBudget.getText())
        );
        boolean reponse;
        try {
            reponse = uneMissionDAO.modifier(missionModif);
            if (reponse) {
                JOptionPane jop1;
                jop1 = new JOptionPane();
                jop1.showMessageDialog(null, "Modification reussie", "Information", JOptionPane.INFORMATION_MESSAGE);
            }
        MenuMission menu = new MenuMission();
        menu.setVisible(true);
        ModifierMission.this.dispose();
        } catch (SQLException ex) {
            System.getLogger(ModifierMission.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

